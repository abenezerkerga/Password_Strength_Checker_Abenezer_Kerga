import string
import getpass

def check_password(password):
    score = 0
    feedback = []

    # Check password length
    if len(password) >= 12:
        score += 2
    elif len(password) >= 8:
        score += 1
    else:
        feedback.append("Use at least 8 characters if possible.")

    # Check character variety
    if any(c.islower() for c in password):
        score += 1
    else:
        feedback.append("Add a lowercase letter.")

    if any(c.isupper() for c in password):
        score += 1
    else:
        feedback.append("Add an uppercase letter.")

    if any(c.isdigit() for c in password):
        score += 1
    else:
        feedback.append("Consider adding a number.")

    if any(c in string.punctuation for c in password):
        score += 1
    else:
        feedback.append("Consider adding a symbol.")

    # Check common weak passwords
    common_passwords = {
        "PASSWORD","password", "password123","PASSWORD123", "12345678",
        "qwerty123", "QWERTY123", "admin123", "ADMIN123", "letmein","LETMEIN"
    }

    if password.lower() in common_passwords:
        score = 0
        feedback.append("This is a commonly used weak password.")

    # Give a result
    if score >= 6 and len(password) >= 12:
        strength = "Strong"
    elif score >= 4 and len(password) >= 8:
        strength = "Moderate"
    else:
        strength = "Weak"

    return strength, feedback


def main():
    print("=== Password Strength Checker ===")

    while True:
        password = getpass.getpass("Enter a test password: ")

        strength, feedback = check_password(password)

        print("\nResult:", strength)

        if feedback:
            print("\nSuggestions:")
            for suggestion in feedback:
                print("-", suggestion)
        else:
            print("Good job! It meets the basic checks.")

        choice = input(
            "\nDo you want to check another password? [Y/N]: "
        ).strip().lower()

        if choice == "y":
            continue
        elif choice == "n":
            print("Thank you!")
            break
        else:
            print("Invalid choice. Please enter Y or N.")


if __name__ == "__main__":
    main()